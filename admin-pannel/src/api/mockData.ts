// Helper for simulated network delay with AbortSignal support
export function delay(ms: number = 400, signal?: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    if (signal?.aborted) {
      return reject(new DOMException('Query was aborted', 'AbortError'));
    }

    const timer = setTimeout(() => {
      resolve();
    }, ms);

    if (signal) {
      signal.addEventListener('abort', () => {
        clearTimeout(timer);
        reject(new DOMException('Query was aborted', 'AbortError'));
      });
    }
  });
}

